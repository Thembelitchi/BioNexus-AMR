#!/usr/bin/env python3
"""Export the BioNexus knowledge graph as a Cypher script, or load one back.

    python tools/export_graph.py export [--out ../graph/bionexus-demo.cypher]
    python tools/export_graph.py load   [--file ../graph/bionexus-demo.cypher]

The script holds the schema (constraints and indexes), every node and every
relationship with all properties, and runs on any Neo4j 5 or later
instance, including Aura, with ``cypher-shell -f`` or the ``load`` command
above. Output is deterministic: nodes are written in key order, so exports
of the same graph are byte-identical and diff cleanly.

Connection settings (NEO4J_URI etc.) come from the environment. ``load``
expects an empty database; it refuses to run otherwise.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

BACKEND = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(BACKEND))

from neo4j.time import Date, DateTime  # noqa: E402

from bionexus.config import Settings, configure_logging  # noqa: E402
from bionexus.db import GraphClient  # noqa: E402
from bionexus.schema import CONSTRAINTS, INDEXES  # noqa: E402

BATCH = 500
# Temporary label and property linking relationships to their nodes during
# loading; both are removed at the end of the script.
IMPORT_LABEL = "BioNexusImport"
IMPORT_ID = "import_id"
_IDENTIFIER = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


def node_keys() -> dict[str, str]:
    """Label -> uniquely constrained key property, from the schema."""
    keys = {}
    for body in CONSTRAINTS.values():
        match = re.match(r"FOR \(n:(\w+)\) REQUIRE n\.(\w+) IS UNIQUE", body)
        keys[match[1]] = match[2]
    return keys


def literal(value) -> str:
    """Render a property value as a Cypher literal."""
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, float):
        if value != value or value in (float("inf"), float("-inf")):
            raise ValueError(f"cannot export non-finite float {value}")
        return repr(value)
    if isinstance(value, str):
        escaped = value.replace("\\", "\\\\").replace("'", "\\'").replace("\n", "\\n").replace("\r", "\\r")
        return f"'{escaped}'"
    if isinstance(value, DateTime):
        if value.tzinfo is None:
            return f"localdatetime('{value.iso_format()}')"
        return f"datetime('{value.iso_format()}')"
    if isinstance(value, Date):
        return f"date('{value.iso_format()}')"
    if isinstance(value, (list, tuple)):
        return "[" + ", ".join(literal(v) for v in value) + "]"
    raise TypeError(f"cannot export {type(value).__name__} value {value!r}")


def _name(name: str) -> str:
    return name if _IDENTIFIER.match(name) else "`" + name.replace("`", "``") + "`"


def _map(props: dict) -> str:
    return "{" + ", ".join(f"{_name(k)}: {literal(v)}" for k, v in sorted(props.items())) + "}"


def _batches(rows: list[str]):
    for start in range(0, len(rows), BATCH):
        yield rows[start:start + BATCH]


def export_cypher(client: GraphClient) -> str:
    keys = node_keys()
    nodes = client.query("MATCH (n) RETURN elementId(n) AS eid, labels(n) AS labels, properties(n) AS props")
    unknown = {tuple(n["labels"]) for n in nodes if len(n["labels"]) != 1 or n["labels"][0] not in keys}
    if unknown:
        raise SystemExit(f"nodes without a single constrained label: {sorted(unknown)}")
    nodes.sort(key=lambda n: (n["labels"][0], str(n["props"][keys[n["labels"][0]]])))
    import_ids = {n["eid"]: i for i, n in enumerate(nodes)}

    rels = client.query(
        "MATCH (a)-[r]->(b) RETURN elementId(a) AS a, elementId(b) AS b, type(r) AS type, properties(r) AS props"
    )
    for r in rels:
        r["s"], r["e"] = import_ids[r["a"]], import_ids[r["b"]]
    rels.sort(key=lambda r: (r["type"], r["s"], r["e"], _map(r["props"])))

    counts: dict[str, int] = {}
    for n in nodes:
        counts[n["labels"][0]] = counts.get(n["labels"][0], 0) + 1
    rel_counts: dict[str, int] = {}
    for r in rels:
        rel_counts[r["type"]] = rel_counts.get(r["type"], 0) + 1

    out = [
        "// BioNexus AMR knowledge graph: schema, nodes and relationships.",
        "// Generated by backend/tools/export_graph.py; regenerate rather than edit.",
        f"// {len(nodes):,} nodes: " + ", ".join(f"{label} {n}" for label, n in sorted(counts.items())),
        f"// {len(rels):,} relationships: " + ", ".join(f"{t} {n}" for t, n in sorted(rel_counts.items())),
        "// Load into an EMPTY database:",
        "//   cypher-shell -u neo4j -p <password> -f bionexus-demo.cypher",
        "",
        "// ---- schema",
    ]
    out += [f"CREATE CONSTRAINT {name} IF NOT EXISTS {body};" for name, body in CONSTRAINTS.items()]
    out += [f"CREATE INDEX {name} IF NOT EXISTS {body};" for name, body in INDEXES.items()]
    out.append(f"CREATE CONSTRAINT bionexus_import_id IF NOT EXISTS FOR (n:{IMPORT_LABEL}) REQUIRE n.{IMPORT_ID} IS UNIQUE;")

    out += ["", "// ---- nodes"]
    for label in sorted(counts):
        rows = [f"  {{i: {import_ids[n['eid']]}, p: {_map(n['props'])}}}" for n in nodes if n["labels"][0] == label]
        for batch in _batches(rows):
            out.append("UNWIND [\n" + ",\n".join(batch) + "\n] AS row")
            out.append(f"CREATE (n:{label}:{IMPORT_LABEL} {{{IMPORT_ID}: row.i}}) SET n += row.p;")

    out += ["", "// ---- relationships"]
    for rel_type in sorted(rel_counts):
        rows = [f"  {{s: {r['s']}, e: {r['e']}, p: {_map(r['props'])}}}" for r in rels if r["type"] == rel_type]
        for batch in _batches(rows):
            out.append("UNWIND [\n" + ",\n".join(batch) + "\n] AS row")
            out.append(f"MATCH (a:{IMPORT_LABEL} {{{IMPORT_ID}: row.s}}), (b:{IMPORT_LABEL} {{{IMPORT_ID}: row.e}})")
            out.append(f"CREATE (a)-[r:{_name(rel_type)}]->(b) SET r += row.p;")

    out += [
        "",
        "// ---- remove the temporary import label",
        f"MATCH (n:{IMPORT_LABEL}) REMOVE n:{IMPORT_LABEL}, n.{IMPORT_ID};",
        "DROP CONSTRAINT bionexus_import_id IF EXISTS;",
        "",
    ]
    return "\n".join(out)


def statements(script: str) -> list[str]:
    """Split a script written by export_cypher into statements.

    Every statement ends with ';' at the end of a line, and string literals
    never contain a raw newline, so this split is exact for these files.
    """
    body = "\n".join(line for line in script.splitlines() if not line.startswith("//"))
    return [s.strip() for s in re.split(r";\s*$", body, flags=re.M) if s.strip()]


def load_cypher(client: GraphClient, script: str) -> int:
    existing = client.query("MATCH (n) RETURN count(n) AS n")[0]["n"]
    if existing:
        raise SystemExit(f"database is not empty ({existing} nodes); load into an empty database")
    todo = statements(script)
    for statement in todo:
        # Schema and data statements must run in separate transactions.
        client.write(lambda tx, s=statement: tx.run(s).consume())
    return len(todo)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    commands = parser.add_subparsers(dest="command", required=True)
    p_export = commands.add_parser("export", help="write the graph as a Cypher script")
    p_export.add_argument("--out", type=Path, default=BACKEND.parent / "graph" / "bionexus-demo.cypher")
    p_load = commands.add_parser("load", help="load a Cypher script into an empty database")
    p_load.add_argument("--file", type=Path, default=BACKEND.parent / "graph" / "bionexus-demo.cypher")
    args = parser.parse_args()

    settings = Settings.from_env()
    configure_logging(settings.log_level)
    with GraphClient(settings) as client:
        if args.command == "export":
            args.out.parent.mkdir(parents=True, exist_ok=True)
            args.out.write_text(export_cypher(client), encoding="utf-8")
            print(f"wrote {args.out} ({args.out.stat().st_size / 1024:.0f} KiB)")
        else:
            count = load_cypher(client, args.file.read_text(encoding="utf-8"))
            print(f"ran {count} statements from {args.file}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
